// Generate seats layout (Rows A to H, columns 1 to 9 = 72 seats)
export const GENERATE_SEAT_MAP = (): Seat[] => {
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'];
  const seats: Seat[] = [];

  rows.forEach((row, rowIndex) => {
    for (let col = 1; col <= 9; col++) {
      const id = `${row}${col}`;
      let tier: Seat['tier'] = 'Standard';
      let price = 14.50;

      if (rowIndex < 2) {
        tier = 'VIP Recliner';
        price = 22.00;
      } else if (rowIndex < 4) {
        tier = 'Premium';
        price = 18.50;
      } else if (rowIndex < 6) {
        tier = 'Executive';
        price = 16.00;
      } else {
        tier = 'Standard';
        price = 14.00;
      }

      const isWheelchair = (row === 'H' && (col === 1 || col === 9));

      seats.push({
        id,
        row,
        col,
        tier,
        price,
        isWheelchair,
      });
    }
  });

  return seats;
};

